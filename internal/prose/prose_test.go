// The marker list is ordered longest first, and a marker that is a prefix of
// another is what that ordering exists for.
func TestStrip(t *testing.T) {
	for _, c := range []struct{ line, want string }{
		{"// the caller holds the lock", "the caller holds the lock"},
		{"/// a rust doc line", "a rust doc line"},
		{"//! an inner rust doc", "an inner rust doc"},
		{"# a shell comment", "a shell comment"},
		{"#!/usr/bin/env bash", "/usr/bin/env bash"},
		{"-- a sql comment", "a sql comment"},
		{"/* a block opener */", "a block opener"},
		{" *  a continuation line", "a continuation line"},
		{`"""Double v."""`, "Double v."},
		{`r"""a raw docstring"""`, "a raw docstring"},
		{"'''a single-quoted docstring'''", "a single-quoted docstring"},
		{"", ""},
		{"//", ""},
		{"no marker at all", "no marker at all"},
		// The closing and opening lines of a block comment carry nothing but
		// markers, and used to keep half of one: `*/` lost its star to the
		// continuation marker and kept the slash, `/**` kept the star.
		{"*/", ""},
		{" */", ""},
		{"**/", ""},
		{"/**", ""},
		{"/** a javadoc opener", "a javadoc opener"},
		{" * a continuation ending the block */", "a continuation ending the block"},
	} {
		if got := Strip(c.line); got != c.want {
			t.Errorf("Strip(%q) = %q, want %q", c.line, got, c.want)
		}
	}
}

// One marker is removed, not every marker: a commented-out comment keeps the
// inner one, which is what tells the rules it was code.
func TestStripRemovesOneMarker(t *testing.T) {
	if got := Strip("// // timeout = 5"); got != "// timeout = 5" {
		t.Errorf("Strip stripped past the first marker: %q", got)
	}
}

// Anchored to the start of a line, so prose that mentions a licence is not one.
func TestNotice(t *testing.T) {
	for _, c := range []struct {
		body string
		want bool
	}{
		{"Copyright 2009 The Go Authors. All rights reserved.", true},
		{"SPDX-License-Identifier: BSD-3-Clause", true},
		{"Licensed under the Apache License, Version 2.0", true},
		{"get the copyright year from the header", false},
		{"the file this reads is licensed under a notice we preserve", false},
		{"double returns v twice over.", false},
		{"", false},
	} {
		if got := Notice(c.body); got != c.want {
			t.Errorf("Notice(%q) = %v, want %v", c.body, got, c.want)
		}
	}
}

// The FreeBSD libm headers Go carries open with a description and reach their
// notice several lines in, so the match cannot be anchored to the comment.
func TestNoticeFoundBelowTheFirstLine(t *testing.T) {
	body := "\n" +
		"__ieee754_log(x)\n" +
		"Return the logarithm of x\n" +
		"\n" +
		"Copyright (C) 1993 by Sun Microsystems, Inc. All rights reserved.\n" +
		"\n" +
		"Permission to use, copy, modify, and distribute this software\n"
	if !Notice(body) {
		t.Error("a notice five lines into a comment went unrecognised")
	}
}

// Indented differs from Strip in exactly one way: what follows the marker keeps
// its shape, so a commented-out block still parses as one.
func TestIndented(t *testing.T) {
	for _, c := range []struct{ line, want string }{
		{"  # resources:", "resources:"},
		{"  #   limits:", "  limits:"},
		{"\t//     cpu: 100m", "    cpu: 100m"},
		{"# ", ""},
		{"#", ""},
		{"  /* var x = 1 */", "var x = 1 "},
	} {
		if got := Indented(c.line); got != c.want {
			t.Errorf("Indented(%q) = %q, want %q", c.line, got, c.want)
		}
	}
}

func TestDedent(t *testing.T) {
	for _, c := range []struct{ text, want string }{
		{"    a\n      b\n    c", "a\n  b\nc"},
		{"a\n  b", "a\n  b"},
		{"    a\n\n    b", "a\n\nb"},
		{"", ""},
		{"   ", "   "},
	} {
		if got := Dedent(c.text); got != c.want {
			t.Errorf("Dedent(%q) = %q, want %q", c.text, got, c.want)
		}
	}
}

// A blank line has no indentation and must not be read as sharing none, or a
// docstring with a paragraph break dedents by nothing at all.
func TestDedentIgnoresBlankLines(t *testing.T) {
	if got := Dedent("    first\n\n    second"); got != "first\n\nsecond" {
		t.Errorf("a blank line set the shared indent: %q", got)
	}
}

