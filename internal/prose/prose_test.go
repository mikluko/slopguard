// A keyword decides only where it opens the line. Prose that uses one as an
// ordinary word is prose, and English opens sentences with "if" and "for"
// often enough that reading them anywhere would exempt nothing.
func TestCodeReadsTheFirstWordOnly(t *testing.T) {
	if Code("the type of v is not checked here") {
		t.Error("a keyword in the middle of a sentence read as code")
	}
}
