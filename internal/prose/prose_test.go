// PEP 263 writes its encoding line with dashes on both sides, and the dashes
// go with the markers, so what the prefix list has to carry is what survives
// that trim rather than what was written.
func TestDirectiveEncodingLine(t *testing.T) {
	if !Directive("# -*- coding: utf-8 -*-") {
		t.Error("the PEP 263 encoding line read as prose")
	}
}

// Padded on both ends, which is what lets a caller match a phrase as words by
// searching for it with its spaces.
func TestNormalize(t *testing.T) {
	for _, c := range []struct{ text, want string }{
		{"Kept for backwards compatibility.", " kept for backwards compatibility "},
		{"v1/v2 clients", " v1 v2 clients "},
		{"   ", " "},
		{"", " "},
	} {
		if got := Normalize(c.text); got != c.want {
			t.Errorf("Normalize(%q) = %q, want %q", c.text, got, c.want)
		}
	}
	if h := Normalize("this is kept for compatibility"); !strings.Contains(h, " kept for ") {
		t.Errorf("a phrase did not match as words: %q", h)
	}
	// The padding is what stops a phrase from matching inside a longer word.
	if h := Normalize("overkept forwards"); strings.Contains(h, " kept for ") {
		t.Errorf("a phrase matched across word boundaries: %q", h)
	}
}

// The cases a full stop does not end a sentence in: an abbreviation, an
// initial, a version number, and a following word that carries on in lower
// case.
func TestSentences(t *testing.T) {
	for _, c := range []struct {
		text string
		want int
	}{
		{"double returns v twice over.", 1},
		{"double returns v twice over. It panics when v overflows.", 2},
		{"no terminator at all", 0},
		{"a list, e.g. this one, is not two sentences.", 1},
		{"see R. Smith for the derivation.", 1},
		{"needs Go 1.21. or newer", 0},
		{"Ends here! And here? Yes.", 3},
		{"", 0},
	} {
		if got := Sentences(c.text); got != c.want {
			t.Errorf("Sentences(%q) = %d, want %d", c.text, got, c.want)
		}
	}
}

func TestSplit(t *testing.T) {
	for _, c := range []struct {
		text string
		want []string
	}{
		{"One. Two.", []string{"One.", "Two."}},
		{"Only one.", []string{"Only one."}},
		{"a\n   b", []string{"a b"}},
		{"", nil},
	} {
		got := Split(c.text)
		if len(got) != len(c.want) {
			t.Errorf("Split(%q) = %q, want %q", c.text, got, c.want)
			continue
		}
		for i := range got {
			if got[i] != c.want[i] {
				t.Errorf("Split(%q)[%d] = %q, want %q", c.text, i, got[i], c.want[i])
			}
		}
	}
}

// Sentences counts terminators and Split returns pieces, so text that trails
// off unterminated has one more piece than it has sentences. A caller reading
// either as the other is off by one on exactly the comments that do not end in
// a full stop, which is most of the one-liners in any codebase.
func TestSplitCountsOneMoreWhenUnterminated(t *testing.T) {
	for _, text := range []string{
		"double returns v twice over. it is not checked",
		"multiply it by two",
		"One. Two.",
		"",
	} {
		pieces, count := len(Split(text)), Sentences(text)
		if strings.HasSuffix(strings.TrimSpace(text), ".") || text == "" {
			if pieces != count {
				t.Errorf("%q: %d pieces against %d sentences", text, pieces, count)
			}
			continue
		}
		if pieces != count+1 {
			t.Errorf("%q: %d pieces against %d sentences, want one more", text, pieces, count)
		}
	}
}

func TestOpening(t *testing.T) {
	long := []string{"one", "two", "three", "four", "five"}
	if got := Opening(long); len(got) != 3 {
		t.Errorf("Opening kept %d sentences, want 3", len(got))
	}
	short := []string{"one", "two"}
	if got := Opening(short); len(got) != 2 {
		t.Errorf("Opening shortened a comment that was already short: %q", got)
	}
	if got := Opening(nil); got != nil {
		t.Errorf("Opening(nil) = %q", got)
	}
}

